import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const repo = 'D:/trackeep/trackeep-product/trackeep-thoradar';
const html = readFileSync(`${repo}/index.html`, 'utf8');
const head = execFileSync('git', ['-C', repo, 'show', 'HEAD:index.html'], { encoding: 'utf8' });
const checks = [];
const check = (name, pass) => { checks.push({ name, pass: !!pass }); console.log(`${pass ? 'PASS' : 'FAIL'} ${name}`); };
check('old mixed-case brand removed', !html.includes('ThorRadar'));
check('old decorative subtitle removed', !html.includes('THORACIC SIGNAL DESK'));
check('old Chinese footer removed', !html.includes('程序生成 · 无人审校'));
check('old English footer removed', !html.includes('Auto-generated · not human-reviewed'));
check('footer translation key removed', !html.includes('foot.note'));
check('Chinese brand subtitle exact', html.includes("'brand.sub':'胸科医学文献 · 每日扫描与个性化追踪'"));
check('English brand subtitle exact', html.includes("'brand.sub':'Thoracic Medical Literature · Daily Scanning and Personalized Tracking'"));
check('Chinese document title exact', html.includes("'doc.title':'Thoradar · 滚动信号场'"));
check('English document title exact', html.includes("'doc.title':'Thoradar · Rolling Signal Field'"));
check('brand subtitle is translated', html.includes('class="brand-sub" data-i18n="brand.sub"'));
check('metadata uses the selected brand', html.includes('胸科雷达 Thoradar') && html.includes('og:title" content="Thoradar · 滚动信号场"'));
const siteLine = s => s.match(/^[ \t]*const SITE_DATA = [^\r\n]+/m)?.[0];
check('official SITE_DATA unchanged', siteLine(html) === siteLine(head));
const result = { checks, summary: { passed: checks.filter(x => x.pass).length, failed: checks.filter(x => !x.pass).length } };
writeFileSync(`${repo}/docs/tasks/T1128-BRANDING/content-check.json`, JSON.stringify(result, null, 2) + '\n');
console.log('SUMMARY ' + JSON.stringify(result.summary));
if (result.summary.failed) process.exitCode = 1;
