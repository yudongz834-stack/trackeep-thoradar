import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseOfficialData, splitOfficialData } from '../../../tests/smooth/official-data.mjs';
const repo = fileURLToPath(new URL('../../../', import.meta.url));
const out = join(dirname(fileURLToPath(import.meta.url)), 'ux-parent.html');
const git = (...args) => execFileSync('git', ['-C', repo, ...args], { encoding: 'utf8', maxBuffer: 8 * 1024 * 1024 });
const head = git('rev-parse', 'HEAD').trim();
const parent = git('rev-parse', `${head}^1`).trim();
const parentPage = splitOfficialData(git('show', `${parent}:index.html`));
const currentPage = splitOfficialData(git('show', `${head}:index.html`));
const currentData = parseOfficialData(currentPage.block);
const baseline = parentPage.before + currentPage.block + parentPage.after;
const prepared = splitOfficialData(baseline);
assert.equal(prepared.before, parentPage.before);
assert.equal(prepared.after, parentPage.after);
assert.equal(prepared.block, currentPage.block);
writeFileSync(out, baseline, { flag: 'wx' });
console.log(JSON.stringify({ revision: head, parent, output: out, briefingDate: currentData.briefing_date, paperCount: currentData.papers.length }));
